    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        try {
        modelo.Siniestro s = new modelo.Siniestro();
        s.setNumReclamo(txtNumeroReclamo.getText().trim());
        s.setIdPoliza(Integer.parseInt(txtIDpoliza.getText().trim()));
        s.setFechaOcurrencia(java.sql.Timestamp.valueOf(txtFechaOcurrencia.getText().trim()));
        s.setDescripcionHechos(txtDescripcion.getText().trim());
        s.setMontoReclamado(Double.parseDouble(txtMontoReclamado.getText().trim()));
        s.setMontoAprobado(Double.parseDouble(txtMontoAprobado.getText().trim()));
        s.setEstadoReclamo(cboEstado.getSelectedItem().toString());

        if (dao.insertar(s)) {
            javax.swing.JOptionPane.showMessageDialog(null, "Siniestro registrado exitosamente.");
            cargarDatos("");
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al registrar el siniestro.");
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(null, "Verifique los datos (Fecha debe ser YYYY-MM-DD HH:MM:SS): " + e.getMessage());
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed
        // TODO add your handling code here:
        if (idSeleccionado == -1) {
        javax.swing.JOptionPane.showMessageDialog(null, "Seleccione un registro de la tabla para editar.");
        return;
    }

    try {
        modelo.Siniestro s = new modelo.Siniestro();
        s.setIdSiniestro(idSeleccionado);
        s.setNumReclamo(txtNumeroReclamo.getText().trim());
        s.setIdPoliza(Integer.parseInt(txtIDpoliza.getText().trim()));
        s.setFechaOcurrencia(java.sql.Timestamp.valueOf(txtFechaOcurrencia.getText().trim()));
        s.setDescripcionHechos(txtDescripcion.getText().trim());
        s.setMontoReclamado(Double.parseDouble(txtMontoReclamado.getText().trim()));
        s.setMontoAprobado(Double.parseDouble(txtMontoAprobado.getText().trim()));
        s.setEstadoReclamo(cboEstado.getSelectedItem().toString());

        if (dao.actualizar(s)) {
            javax.swing.JOptionPane.showMessageDialog(null, "Siniestro actualizado correctamente.");
            cargarDatos("");
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al actualizar.");
        }
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(null, "Error en los datos de edición: " + e.getMessage());
    }
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarActionPerformed
        // TODO add your handling code here:
        if (idSeleccionado == -1) {
        javax.swing.JOptionPane.showMessageDialog(null, "Seleccione un registro de la tabla para eliminar.");
        return;
    }

    int resp = javax.swing.JOptionPane.showConfirmDialog(null, "¿Está seguro de eliminar este reclamo?", "Confirmar", javax.swing.JOptionPane.YES_NO_OPTION);
    if (resp == javax.swing.JOptionPane.YES_OPTION) {
        if (dao.eliminar(idSeleccionado)) {
            javax.swing.JOptionPane.showMessageDialog(null, "Siniestro eliminado.");
            cargarDatos("");
            limpiarCampos();
        } else {
            javax.swing.JOptionPane.showMessageDialog(null, "Error al eliminar el siniestro.");
        }
    }
    }//GEN-LAST:event_btnEliminarActionPerformed

