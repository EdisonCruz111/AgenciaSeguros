    private void tablaSiniestrosMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_tablaSiniestrosMouseClicked
        // TODO add your handling code here:
        int fila = tablaSiniestros.getSelectedRow();
    
    if (fila >= 0) {
        // Obtenemos el ID de la fila seleccionada
        idSeleccionado = Integer.parseInt(tablaSiniestros.getValueAt(fila, 0).toString());
        
        // Pasamos cada celda de la tabla a su campo de texto correspondiente
        txtNumeroReclamo.setText(tablaSiniestros.getValueAt(fila, 1).toString());
        txtIDpoliza.setText(tablaSiniestros.getValueAt(fila, 2).toString());
        txtFechaOcurrencia.setText(tablaSiniestros.getValueAt(fila, 3).toString());
        
        Object fechaReporte = tablaSiniestros.getValueAt(fila, 4);
        txtFechaReporte.setText(fechaReporte != null ? fechaReporte.toString() : "");
        
        txtDescripcion.setText(tablaSiniestros.getValueAt(fila, 5).toString());
        txtMontoReclamado.setText(tablaSiniestros.getValueAt(fila, 6).toString());
        txtMontoAprobado.setText(tablaSiniestros.getValueAt(fila, 7).toString());
        
        if (tablaSiniestros.getValueAt(fila, 8) != null) {
            cboEstado.setSelectedItem(tablaSiniestros.getValueAt(fila, 8).toString());
        }
    }
    }//GEN-LAST:event_tablaSiniestrosMouseClicked

