    private void listarClientes(String filtro) {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("ID");
        modelo.addColumn("Identificación");
        modelo.addColumn("Nombre Completo");
        modelo.addColumn("Teléfono");
        modelo.addColumn("Correo");
        modelo.addColumn("Dirección");
        modelo.addColumn("Estado");

        List<Cliente> lista = dao.listar(filtro);

       for (Cliente c : lista) {
        Object[] fila = new Object[7]; 
        fila[0] = c.getIdCliente();
        fila[1] = c.getDni();
        fila[2] = c.getNombre(); 
        fila[3] = c.getTelefono();
        fila[4] = c.getCorreo();
        fila[5] = c.getDireccion();
        fila[6] = c.isEstado() ? "Activo" : "Inactivo";
        modelo.addRow(fila);
    }

    tablaClientes.setModel(modelo);
}

    // Vaciar formulario y reiniciar variables
    private void limpiarFormulario() {
        idClienteSeleccionado = 0;
        txtDNI.setText("");
        txtNombre.setText("");
        txtCorreo.setText("");
        txtTelefono.setText("");
        txtDireccion.setText("");
        chkEstado.setSelected(true);
        tablaClientes.clearSelection();
    }

    private void seleccionarFilaTabla() {
        int fila = tablaClientes.getSelectedRow();
    if (fila != -1) {
        idClienteSeleccionado = Integer.parseInt(tablaClientes.getValueAt(fila, 0).toString());
        txtDNI.setText(tablaClientes.getValueAt(fila, 1).toString());            // Identificación
        txtNombre.setText(tablaClientes.getValueAt(fila, 2).toString());         // Nombre Completo
        txtTelefono.setText(tablaClientes.getValueAt(fila, 3).toString());       // Teléfono
        txtCorreo.setText(tablaClientes.getValueAt(fila, 4).toString());         // Correo
        txtDireccion.setText(tablaClientes.getValueAt(fila, 5).toString());      // Dirección
        
        String estadoStr = tablaClientes.getValueAt(fila, 6).toString();        // Estado
        chkEstado.setSelected(estadoStr.equalsIgnoreCase("Activo"));
    }
}

