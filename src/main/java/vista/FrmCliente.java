    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
        // TODO add your handling code here:
    if (txtDNI.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "El DNI y Nombre son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Cliente c = new Cliente();
    c.setDni(txtDNI.getText().trim());
    c.setNombre(txtNombre.getText().trim());
    c.setCorreo(txtCorreo.getText().trim());
    c.setTelefono(txtTelefono.getText().trim());
    c.setDireccion(txtDireccion.getText().trim());

    if (dao.registrar(c)) {
        JOptionPane.showMessageDialog(this, "Cliente registrado exitosamente.");
        listarClientes("");
        limpiarFormulario();
    } else {
        JOptionPane.showMessageDialog(this, "Error al guardar cliente.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_BtnGuardarActionPerformed

    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
        // TODO add your handling code here:
    if (idClienteSeleccionado == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla para editar.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Cliente c = new Cliente();
    c.setIdCliente(idClienteSeleccionado);
    c.setDni(txtDNI.getText().trim());
    c.setNombre(txtNombre.getText().trim());
    c.setCorreo(txtCorreo.getText().trim());
    c.setTelefono(txtTelefono.getText().trim());
    c.setDireccion(txtDireccion.getText().trim());
    c.setEstado(chkEstado.isSelected());

    if (dao.modificar(c)) {
        JOptionPane.showMessageDialog(this, "Cliente actualizado exitosamente.");
        listarClientes("");
        limpiarFormulario();
    } else {
        JOptionPane.showMessageDialog(this, "Error al modificar cliente.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_BtnEditarActionPerformed

    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
        // TODO add your handling code here:
    if (idClienteSeleccionado == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un cliente de la tabla para deshabilitar.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int opcion = JOptionPane.showConfirmDialog(this, "¿Desea desactivar al cliente seleccionado?", "Confirmación", JOptionPane.YES_NO_OPTION);
    if (opcion == JOptionPane.YES_OPTION) {
        if (dao.cambiarEstado(idClienteSeleccionado, false)) {
            JOptionPane.showMessageDialog(this, "Cliente desactivado correctamente.");
            listarClientes("");
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "Error al cambiar el estado.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_BtnEliminarActionPerformed

