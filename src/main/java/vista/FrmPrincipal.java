    public FrmPrincipal(Usuario usuario) {
        this();
        this.usuarioSesion = usuario;
        
        setTitle("Sistema de Gestión de Seguros - Usuario: " 
                 + usuario.getNombreCompleto() + " [" + usuario.getNombreRol() + "]");
        
        aplicarPermisosPorRol();
    }

    private void aplicarPermisosPorRol() {
        if (usuarioSesion == null) return;

        if (usuarioSesion.getNombreRol().equalsIgnoreCase("Agente")) {
            menuSeguridad.setEnabled(false); 
        }
    }
