    private void listarTiposSeguro(String filtro) {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("ID");
        modelo.addColumn("Nombre");
        modelo.addColumn("Descripción");

        List<TipoSeguro> lista = dao.listar(filtro);

        for (TipoSeguro ts : lista) {
            Object[] fila = new Object[3];
            fila[0] = ts.getIdTipoSeguro();
            fila[1] = ts.getNombre();
            fila[2] = ts.getDescripcion();
            modelo.addRow(fila);
        }

        tablaSeguros.setModel(modelo);
    }

    private void limpiarFormulario() {
        idTipoSeguroSeleccionado = 0;
        txtNombre.setText("");
        txtDescripcion.setText("");
        tablaSeguros.clearSelection();
    }

    private void seleccionarFilaTabla() {
        int fila = tablaSeguros.getSelectedRow();
        if (fila != -1) {
            idTipoSeguroSeleccionado = Integer.parseInt(tablaSeguros.getValueAt(fila, 0).toString());
            txtNombre.setText(tablaSeguros.getValueAt(fila, 1).toString());
            
            Object descObj = tablaSeguros.getValueAt(fila, 2);
            txtDescripcion.setText(descObj != null ? descObj.toString() : "");
        }
    }

