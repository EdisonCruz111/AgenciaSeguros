    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
        // TODO add your handling code here:
        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre del tipo de seguro es obligatorio.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        TipoSeguro ts = new TipoSeguro();
        ts.setNombre(txtNombre.getText().trim());
        ts.setDescripcion(txtDescripcion.getText().trim());

        if (dao.registrar(ts)) {
            JOptionPane.showMessageDialog(this, "Tipo de seguro registrado exitosamente.");
            listarTiposSeguro("");
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar el tipo de seguro.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BtnGuardarActionPerformed

    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
        // TODO add your handling code here:
        if (idTipoSeguroSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para editar.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        if (txtNombre.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "El nombre no puede quedar vacío.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        TipoSeguro ts = new TipoSeguro();
        ts.setIdTipoSeguro(idTipoSeguroSeleccionado);
        ts.setNombre(txtNombre.getText().trim());
        ts.setDescripcion(txtDescripcion.getText().trim());

        if (dao.modificar(ts)) {
            JOptionPane.showMessageDialog(this, "Tipo de seguro actualizado exitosamente.");
            listarTiposSeguro("");
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "Error al modificar el tipo de seguro.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_BtnEditarActionPerformed

    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
        // TODO add your handling code here:
        if (idTipoSeguroSeleccionado == 0) {
            JOptionPane.showMessageDialog(this, "Seleccione un registro de la tabla para eliminar.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }

        int opcion = JOptionPane.showConfirmDialog(this, "¿Desea eliminar el tipo de seguro seleccionado?", "Confirmación", JOptionPane.YES_NO_OPTION);
        if (opcion == JOptionPane.YES_OPTION) {
            if (dao.eliminar(idTipoSeguroSeleccionado)) {
                JOptionPane.showMessageDialog(this, "Tipo de seguro eliminado correctamente.");
                listarTiposSeguro("");
                limpiarFormulario();
            } else {
                JOptionPane.showMessageDialog(this, "No se puede eliminar porque existen pólizas vinculadas a este tipo de seguro.", "Error de Integridad", JOptionPane.ERROR_MESSAGE);
            }
        }
    }//GEN-LAST:event_BtnEliminarActionPerformed

