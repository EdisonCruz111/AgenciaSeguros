    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        // TODO add your handling code here:
        String username = txtUsername.getText().trim();
    String password = new String(txtPassword.getText()).trim();
    String nombre = txtNombreCompleto.getText().trim();
    String correo = txtCorreo.getText().trim();

    if (username.isEmpty() || nombre.isEmpty() || correo.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Complete todos los campos obligatorios.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    ComboItem rolSel = (ComboItem) cboRol.getSelectedItem();
    boolean estado = cboEstado.getSelectedItem().toString().equalsIgnoreCase("Activo");

    Usuario u = new Usuario();
    u.setIdRol(rolSel.getId());
    u.setUsername(username);
    u.setPassword(password);
    u.setNombreCompleto(nombre);
    u.setEmail(correo);
    u.setActivo(estado);

    UsuarioDAO dao = new UsuarioDAO();

    if (idUsuarioSeleccionado == -1) {
        // Guardar nuevo registro (password obligatoria)
        if (password.isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingrese una contraseña para el nuevo usuario.", "Atención", JOptionPane.WARNING_MESSAGE);
            return;
        }
        if (dao.registrar(u)) {
            JOptionPane.showMessageDialog(this, "Usuario registrado correctamente.");
            limpiarFormulario();
            listarUsuarios("");
        } else {
            JOptionPane.showMessageDialog(this, "Error al guardar el usuario.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } else {
        // Modificar registro existente
        u.setIdUsuario(idUsuarioSeleccionado);
        if (dao.modificar(u)) {
            JOptionPane.showMessageDialog(this, "Usuario actualizado correctamente.");
            limpiarFormulario();
            listarUsuarios("");
        } else {
            JOptionPane.showMessageDialog(this, "Error al actualizar el usuario.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_btnGuardarActionPerformed

