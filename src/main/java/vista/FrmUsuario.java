    private void cargarDatosTabla() {
        System.out.println(">>> Valor extraído de la celda: [" + tablaUsuarios.getValueAt(tablaUsuarios.getSelectedRow(), 3) + "]");
    int fila = tablaUsuarios.getSelectedRow();
    
    if (fila >= 0) {
        // Convertir índice si la tabla está ordenada
        int filaModelo = tablaUsuarios.convertRowIndexToModel(fila);

        // 1. Cargar ID y Campos de texto
        idUsuarioSeleccionado = Integer.parseInt(tablaUsuarios.getModel().getValueAt(filaModelo, 0).toString().trim());
        txtUsername.setText(tablaUsuarios.getModel().getValueAt(filaModelo, 1) != null ? tablaUsuarios.getModel().getValueAt(filaModelo, 1).toString().trim() : "");
        txtNombreCompleto.setText(tablaUsuarios.getModel().getValueAt(filaModelo, 2) != null ? tablaUsuarios.getModel().getValueAt(filaModelo, 2).toString().trim() : "");
        
        // Columna 3: Correo
        String correo = tablaUsuarios.getModel().getValueAt(filaModelo, 3) != null ? tablaUsuarios.getModel().getValueAt(filaModelo, 3).toString().trim() : "";
        txtCorreo.setText(correo);
        txtPassword.setText("");

        // 2. Sincronizar cboRol (Columna 4)
        if (tablaUsuarios.getModel().getValueAt(filaModelo, 4) != null) {
            String nombreRolTabla = tablaUsuarios.getModel().getValueAt(filaModelo, 4).toString().trim();
            for (int i = 0; i < cboRol.getItemCount(); i++) {
                Object item = cboRol.getItemAt(i);
                if (item != null && item.toString().trim().equalsIgnoreCase(nombreRolTabla)) {
                    cboRol.setSelectedIndex(i);
                    break;
                }
            }
        }

        // 3. Sincronizar cboEstado (Columna 5)
        if (tablaUsuarios.getModel().getValueAt(filaModelo, 5) != null) {
            String estadoTabla = tablaUsuarios.getModel().getValueAt(filaModelo, 5).toString().trim();
            for (int i = 0; i < cboEstado.getItemCount(); i++) {
                Object item = cboEstado.getItemAt(i);
                if (item != null && item.toString().trim().equalsIgnoreCase(estadoTabla)) {
                    cboEstado.setSelectedIndex(i);
                    break;
                }
            }
        }
    }
}

