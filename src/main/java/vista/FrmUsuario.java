    private void btnActivarDesactivarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnActivarDesactivarActionPerformed
        // TODO add your handling code here:
        int fila = tablaUsuarios.getSelectedRow();
    if (fila < 0) {
        JOptionPane.showMessageDialog(this, "Seleccione un usuario de la tabla.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int id = Integer.parseInt(tablaUsuarios.getValueAt(fila, 0).toString());
    String estadoActual = tablaUsuarios.getValueAt(fila, 5).toString();
    boolean nuevoEstado = !estadoActual.equalsIgnoreCase("Activo");

    String msj = nuevoEstado ? "¿Desea activar este usuario?" : "¿Desea desactivar este usuario?";
    int resp = JOptionPane.showConfirmDialog(this, msj, "Confirmación", JOptionPane.YES_NO_OPTION);

    if (resp == JOptionPane.YES_OPTION) {
        UsuarioDAO dao = new UsuarioDAO();
        if (dao.cambiarEstado(id, nuevoEstado)) {
            JOptionPane.showMessageDialog(this, "Estado cambiado con éxito.");
            limpiarFormulario();
            listarUsuarios("");
        }
    }
    }//GEN-LAST:event_btnActivarDesactivarActionPerformed

