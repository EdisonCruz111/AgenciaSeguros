    private void cargarCombos() {
        // 1. Cargar JComboBox de Pólizas (cboPolizaActiva)
        DefaultComboBoxModel modeloPolizas = new DefaultComboBoxModel();
        String sqlPolizas = "SELECT id_poliza, num_poliza FROM polizas";
        
        try (Connection cn = obtenerConexion();
             PreparedStatement ps = cn.prepareStatement(sqlPolizas);
             ResultSet rs = ps.executeQuery()) {
            
            while (rs.next()) {
                // CORREGIDO: Se usa "num_poliza" para que coincida con el SELECT
                modeloPolizas.addElement(new ItemCombo(rs.getInt("id_poliza"), "Póliza: " + rs.getString("num_poliza")));
            }
            cboPolizaActiva.setModel(modeloPolizas);
            
        } catch (SQLException e) {
            System.err.println("Error al cargar pólizas en combo: " + e.getMessage());
        }

        // 2. Cargar JComboBox de Métodos de Pago (cboMetodoPago)
        DefaultComboBoxModel modeloMetodos = new DefaultComboBoxModel();
        String sqlMetodos = "SELECT id_metodo, nombre FROM metodos_pago";
        
        try (Connection cn = obtenerConexion();
             PreparedStatement ps = cn.prepareStatement(sqlMetodos);
             ResultSet rs = ps.executeQuery()) {
            
            while (rs.next()) {
                modeloMetodos.addElement(new ItemCombo(rs.getInt("id_metodo"), rs.getString("nombre")));
            }
            cboMetodoPago.setModel(modeloMetodos);
            
        } catch (SQLException e) {
            System.err.println("Error al cargar métodos de pago en combo: " + e.getMessage());
        }
    }

    // Clase auxiliar pequeña para manejar los IDs dentro de los JComboBox limpiamente
