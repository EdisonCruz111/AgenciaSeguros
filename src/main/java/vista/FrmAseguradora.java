    private void BtnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnGuardarActionPerformed
        // TODO add your handling code here:
    if (txtRTN.getText().trim().isEmpty() || txtNombre.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "El RTN y el Nombre Comercial son obligatorios.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Aseguradora a = new Aseguradora();
    a.setRtn(txtRTN.getText().trim());
    a.setNombreComercial(txtNombre.getText().trim());
    a.setContactoPrincipal(txtContacto.getText().trim());
    a.setTelefono(txtTelefono.getText().trim());
    a.setCorreo(txtCorreo.getText().trim());

    if (dao.registrar(a)) {
        JOptionPane.showMessageDialog(this, "Aseguradora registrada exitosamente.");
        listarAseguradoras("");
        limpiarFormulario();
    } else {
        JOptionPane.showMessageDialog(this, "Error al guardar la aseguradora.", "Error", JOptionPane.ERROR_MESSAGE);
    }

    }//GEN-LAST:event_BtnGuardarActionPerformed

    private void BtnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEditarActionPerformed
        // TODO add your handling code here:
    if (idAseguradoraSeleccionada == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione una aseguradora de la tabla para editar.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    Aseguradora a = new Aseguradora();
    a.setIdAseguradora(idAseguradoraSeleccionada);
    a.setRtn(txtRTN.getText().trim());
    a.setNombreComercial(txtNombre.getText().trim());
    a.setContactoPrincipal(txtContacto.getText().trim());
    a.setTelefono(txtTelefono.getText().trim());
    a.setCorreo(txtCorreo.getText().trim());

    if (dao.modificar(a)) {
        JOptionPane.showMessageDialog(this, "Aseguradora actualizada exitosamente.");
        listarAseguradoras("");
        limpiarFormulario();
    } else {
        JOptionPane.showMessageDialog(this, "Error al modificar la aseguradora.", "Error", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_BtnEditarActionPerformed

    private void BtnEliminarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BtnEliminarActionPerformed
        // TODO add your handling code here:
    if (idAseguradoraSeleccionada == 0) {
        JOptionPane.showMessageDialog(this, "Seleccione una aseguradora de la tabla para eliminar.", "Atención", JOptionPane.WARNING_MESSAGE);
        return;
    }

    int opcion = JOptionPane.showConfirmDialog(this, "¿Desea eliminar la aseguradora seleccionada?", "Confirmación", JOptionPane.YES_NO_OPTION);
    if (opcion == JOptionPane.YES_OPTION) {
        if (dao.eliminar(idAseguradoraSeleccionada)) {
            JOptionPane.showMessageDialog(this, "Aseguradora eliminada correctamente.");
            listarAseguradoras("");
            limpiarFormulario();
        } else {
            JOptionPane.showMessageDialog(this, "No se puede eliminar la aseguradora porque tiene pólizas vinculadas.", "Error de Integridad", JOptionPane.ERROR_MESSAGE);
        }
    }
    }//GEN-LAST:event_BtnEliminarActionPerformed

