        private void listarAseguradoras(String filtro) {
        DefaultTableModel modelo = new DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false;
            }
        };

        modelo.addColumn("ID");
        modelo.addColumn("RTN");
        modelo.addColumn("Aseguradora");
        modelo.addColumn("Contacto");
        modelo.addColumn("Teléfono");
        modelo.addColumn("Correo");

        List<Aseguradora> lista = dao.listar(filtro);

        for (Aseguradora a : lista) {
            Object[] fila = new Object[6];
            fila[0] = a.getIdAseguradora();
            fila[1] = a.getRtn();
            fila[2] = a.getNombreComercial();
            fila[3] = a.getContactoPrincipal();
            fila[4] = a.getTelefono();
            fila[5] = a.getCorreo();
            modelo.addRow(fila);
        }

        tablaAseguradoras.setModel(modelo);
    }

    private void limpiarFormulario() {
        idAseguradoraSeleccionada = 0;
        txtRTN.setText("");
        txtNombre.setText("");
        txtContacto.setText("");
        txtTelefono.setText("");
        txtCorreo.setText("");
        tablaAseguradoras.clearSelection();
    }

    private void seleccionarFilaTabla() {
        int fila = tablaAseguradoras.getSelectedRow();
        if (fila != -1) {
            idAseguradoraSeleccionada = Integer.parseInt(tablaAseguradoras.getValueAt(fila, 0).toString());
            txtRTN.setText(tablaAseguradoras.getValueAt(fila, 1).toString());
            txtNombre.setText(tablaAseguradoras.getValueAt(fila, 2).toString());
            txtContacto.setText(tablaAseguradoras.getValueAt(fila, 3).toString());
            txtTelefono.setText(tablaAseguradoras.getValueAt(fila, 4).toString());
            txtCorreo.setText(tablaAseguradoras.getValueAt(fila, 5).toString());
        }
    }
