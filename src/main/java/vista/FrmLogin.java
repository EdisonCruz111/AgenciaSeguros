    private void jBtnIngresarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jBtnIngresarActionPerformed
        // TODO add your handling code here:
        String user = txtUsuario.getText().trim();
        String pass = new String(txtPassword.getPassword()).trim();

        if (user.isEmpty() || pass.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(this, "Por favor llene todos los campos.", "Campos Vacíos", javax.swing.JOptionPane.WARNING_MESSAGE);
        return;
}

        datos.UsuarioDAO dao = new datos.UsuarioDAO();
        modelo.Usuario usuario = dao.validarLogin(user, pass);

        if (usuario != null) {
    javax.swing.JOptionPane.showMessageDialog(this, 
        "¡Bienvenido/a " + usuario.getNombreCompleto() + "!\nRol: " + usuario.getNombreRol(), 
        "Acceso Concedido", 
        javax.swing.JOptionPane.INFORMATION_MESSAGE);

    FrmPrincipal principal = new FrmPrincipal(usuario);
    principal.setVisible(true);

    this.dispose();

} else {
    javax.swing.JOptionPane.showMessageDialog(this, "Usuario o contraseña incorrectos.", "Error de Acceso", javax.swing.JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_jBtnIngresarActionPerformed

